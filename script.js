    function parseDoseDetails(pedText, adultText) {
        const rangeMatch = pedText.match(/([\d\.]+)\s*(?:إلى|-)\s*([\d\.]+)\s*(ملغ|ميكروغرام|وحدة)/);
        const singleMatch = pedText.match(/([\d\.]+)\s*(ملغ|ميكروغرام|وحدة)/);

        let freq = 1;
        let intervalHours = 24;

        if (pedText.includes("كل 4 ساعات") || pedText.includes("6 مرات") || pedText.includes("6 جرعات")) {
            freq = 6; intervalHours = 4;
        } else if (pedText.includes("كل 6 ساعات") || pedText.includes("4 مرات") || pedText.includes("4 جرعات") || pedText.includes("4-6 ساعات")) {
            freq = 4; intervalHours = 6;
        } else if (pedText.includes("كل 8 ساعات") || pedText.includes("3 مرات") || pedText.includes("3 جرعات") || pedText.includes("6-8 ساعات")) {
            freq = 3; intervalHours = 8;
        } else if (pedText.includes("كل 12 ساعة") || pedText.includes("مرتين") || pedText.includes("جرعتين")) {
            freq = 2; intervalHours = 12;
        }

        const isPerDose = pedText.includes("للجرعة");

        // استخراج السقف اليومي للبالغين (Safety Limit) بالميليغرام
        let adultMaxDailyMg = null;
        if (adultText) {
            const gramMatch = adultText.match(/([\d\.]+)\s*غرام/);
            const mgMatches = [...adultText.matchAll(/([\d\.]+)\s*ملغ/g)];
            if (gramMatch) {
                adultMaxDailyMg = parseFloat(gramMatch[1]) * 1000 * (adultText.includes("كل 8") ? 3 : (adultText.includes("كل 6") ? 4 : 2));
            } else if (mgMatches.length > 0) {
                const highestMg = Math.max(...mgMatches.map(m => parseFloat(m[1])));
                const adultFreq = adultText.includes("كل 6") ? 4 : (adultText.includes("كل 8") ? 3 : (adultText.includes("كل 12") || adultText.includes("مرتين") ? 2 : 1));
                adultMaxDailyMg = highestMg * adultFreq;
            }
        }

        if (rangeMatch) {
            return { min: parseFloat(rangeMatch[1]), max: parseFloat(rangeMatch[2]), unit: rangeMatch[3], freq, intervalHours, isPerDose, type: "range", adultMaxDailyMg };
        } else if (singleMatch) {
            return { min: parseFloat(singleMatch[1]), max: parseFloat(singleMatch[1]), unit: singleMatch[2], freq, intervalHours, isPerDose, type: "single", adultMaxDailyMg };
        }
        return null;
    }

    function performDoseCalculation() {
        const weight = parseFloat(weightInput.value);
        if (isNaN(weight) || weight <= 0) {
            calcResult.innerHTML = `<div class="text-danger fw-bold">⚠️ يرجى إدخال وزن صحيح للطفل بالكيلوغرام.</div>`;
            calcResult.classList.remove("d-none");
            return;
        }

        const parsed = parseDoseDetails(currentSelectedDrug.ped, currentSelectedDrug.adult);
        if (!parsed) {
            calcResult.innerHTML = `<div class="fw-semibold">ℹ️ هذا الدواء يعتمد على شريحة عمرية ثابتة (كالبخاخات أو الأكياس)، راجع نص الجرعة أعلاه.</div>`;
            calcResult.classList.remove("d-none");
            return;
        }

        let dailyMin, dailyMax, singleMin, singleMax;
        if (parsed.isPerDose) {
            singleMin = weight * parsed.min;
            singleMax = weight * parsed.max;
            dailyMin = singleMin * parsed.freq;
            dailyMax = singleMax * parsed.freq;
        } else {
            dailyMin = weight * parsed.min;
            dailyMax = weight * parsed.max;
            singleMin = dailyMin / parsed.freq;
            singleMax = dailyMax / parsed.freq;
        }

        const intervalText = parsed.freq === 1 ? "تؤخذ مرة واحدة كل 24 ساعة" : `تؤخذ كل ${parsed.intervalHours} ساعات (${parsed.freq} مرات يومياً)`;

        // حساب حجم الشراب بالـ (ml)
        let suspensionHTML = "";
        if (suspensionSelect.value !== "0" && parsed.unit === "ملغ") {
            const [concMg, concMl] = suspensionSelect.value.split("/").map(Number);
            const mlMin = ((singleMin * concMl) / concMg).toFixed(1);
            const mlMax = ((singleMax * concMl) / concMg).toFixed(1);
            const mlDisplay = parsed.type === "range" ? `${mlMin} إلى ${mlMax} مل` : `${mlMin} مل`;

            suspensionHTML = `
                <div class="mt-3 p-2 px-3 rounded-3 d-flex align-items-center justify-content-between" style="background-color: rgba(123, 189, 232, 0.18); border: 1px dashed #7BBDE8;">
                    <span class="fw-bold">🥄 الحجم المطلوب من المعلق (${concMg} ملغ/${concMl} مل):</span>
                    <span class="fs-5 fw-extrabold" style="color: var(--primary-color);">${mlDisplay} في كل جرعة</span>
                </div>
            `;
        }

        // فحص تنبيهات الأمان القصوى (Safety Limits)
        let safetyHTML = "";
        if (weight >= 45 || (parsed.adultMaxDailyMg && parsed.unit === "ملغ" && dailyMax > parsed.adultMaxDailyMg)) {
            safetyHTML = `
                <div class="safety-alert-danger mt-3">
                    <div class="fw-extrabold mb-1">🚨 تنبيه أمان سريري (تجاوز السقف الأقصى):</div>
                    <div class="small">الجرعة المحسوبة حسب الوزن تقترب من أو تتجاوز السقف اليومي للبالغين (${parsed.adultMaxDailyMg ? parsed.adultMaxDailyMg + ' ملغ/يوم' : 'وزن > 45 كغ'}). <strong>يجب الالتزام بجرعة البالغين المعيارية وعدم تجاوزها.</strong></div>
                </div>
            `;
        }

        const dailyText = parsed.type === "range" ? `${dailyMin.toFixed(1)} إلى ${dailyMax.toFixed(1)} ${parsed.unit}` : `${dailyMin.toFixed(1)} ${parsed.unit}`;
        const singleText = parsed.type === "range" ? `${singleMin.toFixed(1)} إلى ${singleMax.toFixed(1)} ${parsed.unit}` : `${singleMin.toFixed(1)} ${parsed.unit}`;

        calcResult.innerHTML = `
            <div class="row g-2 align-items-center">
                <div class="col-12 col-md-5 border-bottom border-md-bottom-0 pb-2 pb-md-0">
                    <div class="calc-label-title">الجرعة الكلية في اليوم (24 ساعة):</div>
                    <div class="fs-5 fw-extrabold" style="color: var(--primary-color);">${dailyText}</div>
                </div>
                <div class="col-12 col-md-7">
                    <div class="d-flex flex-wrap align-items-center justify-content-between gap-2 mb-1">
                        <span class="calc-label-title">مقدار الجرعة الواحدة:</span>
                        <span class="interval-badge">⏱️ ${intervalText}</span>
                    </div>
                    <div class="fs-4 fw-extrabold text-success">الجرعة الواحدة = ${singleText}</div>
                </div>
            </div>
            ${suspensionHTML}
            ${safetyHTML}
        `;
        calcResult.classList.remove("d-none");
    }

