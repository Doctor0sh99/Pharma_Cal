function loadLocalData() {
    const savedDrugs = localStorage.getItem(DB_STORAGE_KEY);
    if (savedDrugs) {
        try { activeDrugsList = JSON.parse(savedDrugs); }
        catch { activeDrugsList = [...drugsData]; }
    } else {
        activeDrugsList = [...drugsData];
        localStorage.setItem(DB_STORAGE_KEY, JSON.stringify(activeDrugsList));
    }

    const savedFavs = localStorage.getItem(FAV_STORAGE_KEY);
    favoriteIds = savedFavs ? JSON.parse(savedFavs) : [1, 2, 51, 53, 105, 109, 136];
}

function saveDrugsToStorage() {
    localStorage.setItem(DB_STORAGE_KEY, JSON.stringify(activeDrugsList));
}

function toggleFavorite(drugId) {
    const idx = favoriteIds.indexOf(drugId);
    if (idx > -1) favoriteIds.splice(idx, 1);
    else favoriteIds.push(drugId);
    localStorage.setItem(FAV_STORAGE_KEY, JSON.stringify(favoriteIds));
    updateFavBadge();
}

function updateFavBadge() {
    const badge = document.getElementById("favCountBadge");
    if (badge) badge.textContent = favoriteIds.length;
}

// ==================== تطبيع النصوص العربية ====================
function normalizeText(str) {
    if (!str) return "";
    return str
        .toLowerCase()
        .replace(/[أإآ]/g, "ا")
        .replace(/ة/g, "ه")
        .replace(/ى/g, "ي")
        .replace(/[\u064B-\u065F]/g, "")
        .trim();
}

// ==================== إدارة المظهر (Light / Dark) ====================
function initTheme() {
    const savedTheme = localStorage.getItem("bnf_theme") || "light";
    applyTheme(savedTheme);

    const toggleBtn = document.getElementById("themeToggleBtn");
    if (toggleBtn) {
        toggleBtn.addEventListener("click", () => {
            const current = document.documentElement.getAttribute("data-bs-theme");
            const next = current === "dark" ? "light" : "dark";
            applyTheme(next);
            localStorage.setItem("bnf_theme", next);
        });
    }
}

function applyTheme(theme) {
    document.documentElement.setAttribute("data-bs-theme", theme);
    const icon = document.getElementById("themeIcon");
    const text = document.getElementById("themeText");
    if (icon && text) {
        if (theme === "dark") {
            icon.className = "bi bi-sun-fill text-warning";
            text.textContent = "الوضع النهاري";
        } else {
            icon.className = "bi bi-moon-stars-fill";
            text.textContent = "الوضع الليلي";
        }
    }
}

